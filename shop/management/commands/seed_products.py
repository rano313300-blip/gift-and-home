class Command(BaseCommand):
    help = "دسته‌بندی‌ها و محصولات نمونه را می‌سازد (اجرای دوباره، تکراری نمی‌سازد)."

    def handle(self, *args, **opts):
        cats = {}
        for slug, name, order in CATS:
            cats[slug], _ = Category.objects.get_or_create(slug=slug, defaults={"name": name, "order": order})
        created = 0
        for cat, name, price, old, emoji, bg, w, stock, sold, rating, desc in PRODUCTS:
            _, new = Product.objects.get_or_create(
                name=name,
                defaults=dict(category=cats[cat], price=price, old_price=old, emoji=emoji, bg_color=bg,
                              weight_kg=w, stock=stock, sold_count=sold, rating=rating, description=desc),
            )
            created += new
        self.stdout.write(self.style.SUCCESS(f"{created} محصول جدید ساخته شد."))
